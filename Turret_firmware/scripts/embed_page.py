# PlatformIO pre-build script: compacts src/web/page/index.html and gzips it
# into a C array (src/web/page_gz.h) so that the page is part of the firmware:
# no LittleFS, no Internet, always the same version as the firmware (plan §10.2).
# The source stays readable (indented, commented); here it is compacted:
# HTML / CSS comments and JavaScript "//" lines removed, indentation and blank
# lines dropped. No JavaScript rewriting (no dependency): template literals in
# the page must not rely on leading whitespace.
# The header is generated, not versioned; it is only rewritten when it changes.
import gzip
import os
import re

Import("env")  # noqa: F821 (provided by PlatformIO)

BUDGET = 30 * 1024  # plan §10.2: < 30 kB gzip

project = env["PROJECT_DIR"]  # noqa: F821
source = os.path.join(project, "src", "web", "page", "index.html")
target = os.path.join(project, "src", "web", "page_gz.h")


def compact(html):
    html = re.sub(r"<!--.*?-->", "", html, flags=re.S)
    html = re.sub(r"/\*.*?\*/", "", html, flags=re.S)  # CSS comments (the JS has none)
    lines = []
    for line in html.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("//"):
            continue
        lines.append(stripped)
    return "\n".join(lines) + "\n"


with open(source, "r", encoding="utf-8") as f:
    html = f.read()
compacted = compact(html).encode("utf-8")
# mtime=0: identical input gives an identical header (no needless rebuild).
data = gzip.compress(compacted, compresslevel=9, mtime=0)

lines = [
    "// Generated by scripts/embed_page.py from src/web/page/index.html. Do not edit.",
    "#pragma once",
    "#include <Arduino.h>",
    "",
    "static const size_t PAGE_GZ_LEN = %d;" % len(data),
    "static const uint8_t PAGE_GZ[] PROGMEM = {",
]
for i in range(0, len(data), 16):
    lines.append("  " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
lines.append("};")
content = "\n".join(lines) + "\n"

old = None
if os.path.exists(target):
    with open(target, "r") as f:
        old = f.read()
if old != content:
    with open(target, "w", newline="\n") as f:
        f.write(content)

print("embed_page: index.html %d bytes -> %d compacted -> %d bytes gzip%s" % (
    len(html), len(compacted), len(data), "" if len(data) <= BUDGET else " (OVER THE 30 kB BUDGET)"))
